"""The Unicode updater validates downloads before changing the header."""

import io
from pathlib import Path
import runpy
from types import SimpleNamespace
import unittest
from urllib.error import URLError
from unittest.mock import patch


GENERATOR = Path(__file__).resolve().parents[1] / "tools" / "generate-unicode.py"
HASHES = (
	"d62e5bab70ca74f099343f71224fa051cb1fdd61a1ab45c0488c44cfc0b6102e",
	"24c7fed1195c482faaefd5c1e7eb821c5ee1fb6de07ecdbaa64b56a99da22c08",
)
HEADER = """prefix
// BEGIN GENERATED UNICODE RANGES
// Unicode 17.0.0: General_Category Other or Separator, or Default_Ignorable_Code_Point.
// Generated by tools/generate-unicode.py.
inline constexpr std::array<std::pair<char32_t, char32_t>, 1> diagnostic_code_point_ranges{{
	{0x0, 0x1F},
}};
// END GENERATED UNICODE RANGES
suffix
"""


class UnicodeUpdaterTests(unittest.TestCase):
	def test_oversized_download_is_rejected_before_checksum_or_write(self):
		response = io.BytesIO(b"x" * (4 * 1024 * 1024 + 1))
		with patch("urllib.request.urlopen", return_value=response), patch("hashlib.sha256") as checksum, patch.object(Path, "write_text") as write:
			with self.assertRaisesRegex(ValueError, "exceeds the download limit"):
				runpy.run_path(str(GENERATOR))
			checksum.assert_not_called()
			write.assert_not_called()

	def test_incorrect_checksum_leaves_header_untouched(self):
		with patch("urllib.request.urlopen", return_value=io.BytesIO(b"untrusted data")), patch.object(Path, "write_text") as write:
			with self.assertRaisesRegex(ValueError, "Checksum mismatch"):
				runpy.run_path(str(GENERATOR))
			write.assert_not_called()

	def test_network_failure_leaves_header_untouched(self):
		with patch("urllib.request.urlopen", side_effect=URLError("offline")), patch.object(Path, "write_text") as write:
			with self.assertRaises(URLError):
				runpy.run_path(str(GENERATOR))
			write.assert_not_called()

	def test_second_download_failure_leaves_header_untouched(self):
		checksum = SimpleNamespace(hexdigest=lambda: HASHES[0])
		responses = [io.BytesIO(b"0000..001F ; Cc\n"), URLError("offline")]
		with patch("urllib.request.urlopen", side_effect=responses), patch("hashlib.sha256", return_value=checksum), patch.object(Path, "write_text") as write:
			with self.assertRaises(URLError):
				runpy.run_path(str(GENERATOR))
			write.assert_not_called()

	def test_unselected_properties_and_disjoint_ranges_remain_excluded(self):
		checksums = [SimpleNamespace(hexdigest=lambda value=value: value) for value in HASHES]
		responses = [io.BytesIO(b"0020 ; Zs\n0041 ; Lu\nE000..F8FF ; Co\n"), io.BytesIO(b"0041 ; Alphabetic\n200B..200C ; Default_Ignorable_Code_Point\n")]
		with patch("urllib.request.urlopen", side_effect=responses), patch("hashlib.sha256", side_effect=checksums), patch.object(Path, "read_text", return_value=HEADER), patch.object(Path, "write_text") as write:
			result = runpy.run_path(str(GENERATOR))
			self.assertEqual(result["merged"], [(0x20, 0x20), (0x200B, 0x200C), (0xE000, 0xF8FF)])
			self.assertIn("std::pair<char32_t, char32_t>, 3>", write.call_args.args[0])

	def test_comments_and_whitespace_do_not_become_properties(self):
		checksums = [SimpleNamespace(hexdigest=lambda value=value: value) for value in HASHES]
		responses = [io.BytesIO(b"# 0041 ; Cc\n\n 0020 ; Zs # comment ; Lu\n0041 ; Lu\n"), io.BytesIO(b" \t# ignored\n200B ; Default_Ignorable_Code_Point # comment # more\n")]
		with patch("urllib.request.urlopen", side_effect=responses), patch("hashlib.sha256", side_effect=checksums), patch.object(Path, "read_text", return_value=HEADER), patch.object(Path, "write_text"):
			result = runpy.run_path(str(GENERATOR))
			self.assertEqual(result["merged"], [(0x20, 0x20), (0x200B, 0x200B)])

	def test_nested_adjacent_and_duplicate_ranges_merge_without_gaps(self):
		checksums = [SimpleNamespace(hexdigest=lambda value=value: value) for value in HASHES]
		responses = [io.BytesIO(b"0010..001F ; Cc\n0015..0018 ; Cf\n0020 ; Zs\n"), io.BytesIO(b"0010..001F ; Default_Ignorable_Code_Point\n0022 ; Default_Ignorable_Code_Point\n")]
		with patch("urllib.request.urlopen", side_effect=responses), patch("hashlib.sha256", side_effect=checksums), patch.object(Path, "read_text", return_value=HEADER), patch.object(Path, "write_text"):
			result = runpy.run_path(str(GENERATOR))
			self.assertEqual(result["merged"], [(0x10, 0x20), (0x22, 0x22)])

	def test_singletons_and_range_endpoints_cover_unicode_boundaries(self):
		checksums = [SimpleNamespace(hexdigest=lambda value=value: value) for value in HASHES]
		responses = [io.BytesIO(b"0000 ; Cc\n007F..009F ; Cc\n10FFFF ; Cn\n"), io.BytesIO(b"200B..200F ; Default_Ignorable_Code_Point\n")]
		with patch("urllib.request.urlopen", side_effect=responses), patch("hashlib.sha256", side_effect=checksums), patch.object(Path, "read_text", return_value=HEADER), patch.object(Path, "write_text") as write:
			result = runpy.run_path(str(GENERATOR))
			self.assertEqual(result["merged"], [(0, 0), (0x7F, 0x9F), (0x200B, 0x200F), (0x10FFFF, 0x10FFFF)])
			self.assertIn("{0x10FFFF, 0x10FFFF}", write.call_args.args[0])

	def test_unchanged_ranges_preserve_header_timestamp(self):
		checksums = [SimpleNamespace(hexdigest=lambda value=value: value) for value in HASHES]
		responses = [io.BytesIO(b"0000..001F ; Cc\n"), io.BytesIO(b"0000..001F ; Default_Ignorable_Code_Point\n")]
		with patch("urllib.request.urlopen", side_effect=responses), patch("hashlib.sha256", side_effect=checksums), patch.object(Path, "read_text", return_value=HEADER), patch.object(Path, "write_text") as write:
			result = runpy.run_path(str(GENERATOR))
			self.assertEqual(result["merged"], [(0, 31)])
			write.assert_not_called()

	def test_verified_changed_ranges_preserve_surrounding_header(self):
		checksums = [SimpleNamespace(hexdigest=lambda value=value: value) for value in HASHES]
		responses = [io.BytesIO(b"0000..001F ; Cc\n"), io.BytesIO(b"001E..0020 ; Default_Ignorable_Code_Point\n")]
		with patch("urllib.request.urlopen", side_effect=responses), patch("hashlib.sha256", side_effect=checksums), patch.object(Path, "read_text", return_value=HEADER), patch.object(Path, "write_text") as write:
			runpy.run_path(str(GENERATOR))
			write.assert_called_once_with(HEADER.replace("{0x0, 0x1F}", "{0x0, 0x20}"), encoding="utf-8")


if __name__ == "__main__":
	unittest.main()
