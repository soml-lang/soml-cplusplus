/*
Writes a C++ file that checks every conformance case in a constant expression: a valid case must give its canonical bytes, and an invalid case must fail at its line and column. Compiling the file is the test. CMake runs it at build time when Node.js is there:

	node tests/generate-constexpr.js build/constexpr-conformance.cpp
*/
import fs from 'node:fs';
import path from 'node:path';

const root = path.join(import.meta.dirname, 'conformance');
const output = process.argv[2];
const reasons = JSON.parse(fs.readFileSync(path.join(root, 'invalid-reasons.json'), 'utf8'));

// Bytes as a C++ string literal. Each escape ends the literal, so that a following hexadecimal digit is not read as part of it.
function literal(bytes) {
	let text = '"';

	for (const byte of bytes) {
		text += byte < 0x20 || byte >= 0x7F || byte === 0x22 || byte === 0x5C || byte === 0x3F ? `\\x${byte.toString(16).padStart(2, '0')}""` : String.fromCodePoint(byte);
	}

	return `${text}"`;
}

function listFiles(directory) {
	// globSync was slower on this fixture tree with Node.js 26; keep the readdir/filter path.
	return fs.readdirSync(directory, {recursive: true, encoding: 'utf8'}).map(file => path.join(directory, file)).filter(file => file.endsWith('.soml') && !file.endsWith('.canonical.soml') && !file.endsWith('.formatted.soml')).toSorted();
}

let text = `// Generated by tests/generate-constexpr.js from tests/conformance. Do not edit.
#include <soml.hpp>

namespace {

// The literal without its NUL terminator, which a case may also hold in its text.
template<std::size_t size>
consteval std::string_view bytes(const char (&text)[size]) {
	return {text, size - 1};
}

constexpr std::string canonical(std::string_view text) {
	auto value = soml::parse(text);

	if (!value) {
		return "error: " + value.error().message;
	}

	auto written = soml::write_canonical(*value);
	return written ? *written : "write error: " + written.error().message;
}

constexpr bool fails_at(std::string_view text, std::size_t line, std::size_t column) {
	auto value = soml::parse(text);
	return !value && value.error().line == line && value.error().column == column;
}

`;

for (const file of listFiles(path.join(root, 'valid'))) {
	const expected = fs.readFileSync(file.replace(/\.soml$/v, '.canonical.soml'));
	text += `static_assert(canonical(bytes(${literal(fs.readFileSync(file))})) == bytes(${literal(expected)})); // ${path.relative(root, file)}\n`;
}

for (const file of listFiles(path.join(root, 'invalid'))) {
	const name = path.relative(path.join(root, 'invalid'), file).replace(/\.soml$/v, '');
	text += `static_assert(fails_at(bytes(${literal(fs.readFileSync(file))}), ${reasons[name].line}, ${reasons[name].column})); // ${name}\n`;
}

text += '\n} // namespace\n';
fs.writeFileSync(output, text);
