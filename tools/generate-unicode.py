#!/usr/bin/env python3
"""Update SOML's diagnostic character ranges from checksum-pinned Unicode 17 data."""

import hashlib
from pathlib import Path
from urllib.request import urlopen

VERSION = "17.0.0"
MAX_DOWNLOAD_BYTES = 4 * 1024 * 1024
SOURCES = {
	"extracted/DerivedGeneralCategory.txt": "d62e5bab70ca74f099343f71224fa051cb1fdd61a1ab45c0488c44cfc0b6102e",
	"DerivedCoreProperties.txt": "24c7fed1195c482faaefd5c1e7eb821c5ee1fb6de07ecdbaa64b56a99da22c08",
}

ranges = []
for source, expected_hash in SOURCES.items():
	with urlopen(f"https://www.unicode.org/Public/{VERSION}/ucd/{source}", timeout=30) as response:
		data = response.read(MAX_DOWNLOAD_BYTES + 1)
	if len(data) > MAX_DOWNLOAD_BYTES:
		raise ValueError(f"Unicode source exceeds the download limit: {source}")
	if hashlib.sha256(data).hexdigest() != expected_hash:
		raise ValueError(f"Checksum mismatch for {source}")
	for line in data.decode("utf-8").splitlines():
		content = line.partition("#")[0].strip()
		if not content:
			continue
		# Note: Not using map(str.strip, ...) because it was slower on the Unicode property corpus with Python 3.14.
		code_points, property_name, *_ = [part.strip() for part in content.split(";")]
		if source.startswith("extracted/"):
			selected = property_name.startswith(("C", "Z"))
		else:
			selected = property_name == "Default_Ignorable_Code_Point"
		if selected:
			start, separator, end = code_points.partition("..")
			ranges.append((int(start, 16), int(end if separator else start, 16)))

merged = []
for start, end in sorted(ranges):
	if merged and start <= merged[-1][1] + 1:
		merged[-1] = (merged[-1][0], max(end, merged[-1][1]))
	else:
		merged.append((start, end))

start_marker = "// BEGIN GENERATED UNICODE RANGES"
end_marker = "// END GENERATED UNICODE RANGES"
lines = [
	start_marker,
	f"// Unicode {VERSION}: General_Category Other or Separator, or Default_Ignorable_Code_Point.",
	"// Generated by tools/generate-unicode.py.",
	f"inline constexpr std::array<std::pair<char32_t, char32_t>, {len(merged)}> diagnostic_code_point_ranges{{{{",
]
# Note: Not using extend(generator) because it added no consistent benefit for these range lines with Python 3.14.
for start, end in merged:
	lines.append(f"\t{{0x{start:X}, 0x{end:X}}},")
lines.extend(["}};", end_marker])

header = Path(__file__).resolve().parents[1] / "include" / "soml.hpp"
text = header.read_text(encoding="utf-8")
start = text.index(start_marker)
end = text.index(end_marker, start) + len(end_marker)
updated = text[:start] + "\n".join(lines) + text[end:]
if updated != text:
	header.write_text(updated, encoding="utf-8")
print(f"Wrote {len(merged)} Unicode {VERSION} diagnostic ranges")
